"""Native SideFX seam branch. Reads retained L06 caches; never cooks L02-05.

All production geometry is generated by vendor SOPs and original Pegasus HDAs.
NumPy is restricted to comparison evidence. Each checkpoint retains its producer.
"""
import argparse
import json
from pathlib import Path
import hou
import numpy as np
from repair_lesson06_idmap import read, volume, values, lattice, digest, geometry, NAMES, WORLD

ROOT=Path('D:/yacs/work/lesson06-seam-20261018')
SOURCE=Path('D:/yacs/work/lesson06-reviewed-20261018')
HIP=WORLD/'SaCalobra_Pegasus_Lesson06_Seam.hiplc'
CODES=[0,64,128,191,255]

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--verify',action='store_true')
    a=ap.parse_args()
    assert hou.applicationVersionString()=='22.0.466'
    ROOT.mkdir(exist_ok=True)
    hou.setUpdateMode(hou.updateMode.Manual)
    hou.hipFile.load(str(HIP if a.verify else WORLD/'SaCalobra_Pegasus_Lesson06_Reviewed.hiplc'),suppress_save_prompt=True)
    if a.verify:
        g=hou.node('/obj/LESSON06_SEAM')
    else:
        assert not (ROOT/'repair.json').exists(), 'Preserve completed proof'
        if HIP.exists():
            import shutil
            backup=HIP.with_stem(HIP.stem+'_Unverified')
            if not backup.exists():shutil.copy2(HIP,backup)
        g=hou.node('/obj').createNode('geo','LESSON06_SEAM')
        for child in g.children():child.destroy()
    hou.setUpdateMode(hou.updateMode.AutoUpdate)
    report={'status':'IN_PROGRESS','version':hou.applicationVersionString(),'fresh_reopen':a.verify,'checkpoints':{},'inset_m':32,'blur_radius_m':16}

    def node(typ,name,inputs=(),parms=None):
        if a.verify:return g.node(name)
        n=g.createNode(typ,name)
        for i,source in enumerate(inputs):n.setInput(i,source)
        if parms:n.setParms(parms)
        return n

    def file(name,path):return node('file',name,parms={'file':str(path)})
    def keep(source,name,pattern):return node('blast',name,[source],{'group':pattern,'negate':1})
    def checkpoint(producer,name):
        path=ROOT/(name+'.bgeo.sc')
        if a.verify:
            actual=geometry(producer)
            cached=read(path)
            assert len(actual.prims())==len(cached.prims()),name
            for p in actual.prims():
                label=p.attribValue('name')
                assert lattice(p)==lattice(volume(cached,label)),(name,label,'lattice')
                assert p.allVoxelsAsString()==volume(cached,label).allVoxelsAsString(),(name,label,'replay')
        elif not path.exists():
            temp=ROOT/(name+'.pending.bgeo.sc')
            geometry(producer).saveToFile(str(temp))
            temp.replace(path)
        f=file(name+'_CACHE',path)
        if not a.verify:
            f.setComment('Native producer: '+producer.path()+'. Replay with repair_lesson06_seam.py --verify.')
            f.setUserData('native_producer',producer.path())
        report['checkpoints'][name]={'path':str(path),'sha256':digest(path),'producer':producer.path(),'fresh_replay':a.verify,'errors':list(producer.errors()),'warnings':list(producer.warnings())}
        print('CHECKPOINT',name,flush=True)
        return f

    w=file('WORKING_SOURCE',SOURCE/'working/final.bgeo.sc')
    c=file('CONTEXT_SOURCE',SOURCE/'context/final.bgeo.sc')
    wg=read(SOURCE/'working/final.bgeo.sc')
    lat=lattice(volume(wg,'height'));nx,ny,_=lat['resolution']
    ox,_,oz=lat['origin'];dx=lat['x'][0];dz=lat['y'][2]
    sx,sz=nx*dx,-ny*dz;tx=ox+(nx-1)*dx/2;tz=oz+(ny-1)*dz/2
    report['lattice']=lat
    del wg
    wid=keep(w,'WORKING_ID','@name=id')
    cid=keep(c,'CONTEXT_ID','@name=id')
    crop=node('heightfield_crop','CONTEXT_OVERLAP',[cid],{'sizex':sx+16,'sizey':sz+16,'tx':tx,'tz':tz})
    cv=node('convertvdb','CONTEXT_ID_VDB',[crop],{'conversion':'vdb'})
    wv=node('convertvdb','WORKING_REFERENCE_VDB',[wid],{'conversion':'vdb'})
    res=node('vdbresample','NEAREST_CONTEXT_ID',[cv,wv],{'order':'point','mode':'refvdb'})
    dense=node('convertvdb','CONTEXT_ID_VOLUME',[res],{'conversion':'volume'})
    aligned=node('heightfield_layer','ALIGN_CONTEXT_ID',[wid,dense],{'layer':'id','mode':'replace'})
    target=checkpoint(aligned,'context_id_aligned')
    # Real geometry defines the feather boundary; native mask SOP owns the falloff.
    hm=keep(w,'HEIGHT_AND_MASK','@name=height @name=mask')
    box=node('box','INNER_WORKING_RECTANGLE',parms={'sizex':sx-64,'sizey':10000,'sizez':sz-64,'tx':tx,'tz':tz})
    band=node('heightfield_maskbyobject','BORDER_FALLOFF',[hm,box],{'invertmask':1,'blurmethod':'boxblur','blurradius':16,'maxdist':10000})
    bandmask=keep(band,'BORDER_MASK_ONLY','@name=mask')
    feather=checkpoint(bandmask,'border_weight')
    # Restrict the color composite explicitly: height and original masks cannot be changed.
    color=node('heightfield_layer','COLOR_TRANSITION',[w,c,feather],{'layer':'r g b roughness','mode':'replace','masklayer':'mask'})
    colored=checkpoint(color,'color_transition')
    previous=colored
    original=hou.node('/obj/LESSON06_WORKING')
    for index,name in enumerate(NAMES):
        safe=name.replace(' ','_')
        raw=file('ORIGINAL_'+safe.upper(),SOURCE/'working'/(safe+'_mask.bgeo.sc'))
        dec=node(original.node('ID_TO_LAYER').type().name(),'CONTEXT_'+safe.upper(),[target],{'srcname1':'id','dstname1':'mask','id_layer':str(CODES[index])})
        decoded=keep(dec,'CONTEXT_'+safe.upper()+'_MASK','@name=mask')
        mix=node('heightfield_layer','BLEND_'+safe.upper(),[raw,decoded,feather],{'layer':'mask','mode':'replace','masklayer':'mask'})
        blended=checkpoint(mix,'derived_'+safe)
        if a.verify:enc=g.node('ENCODE_'+safe.upper())
        else:
            enc=original.node(safe+'_layer').copyTo(g)
            enc.setName('ENCODE_'+safe.upper())
            enc.setInput(0,previous);enc.setInput(1,blended)
            enc.parm('objpath1').set(original.node('ID_MAP_LAYERS').path())
        previous=checkpoint(enc,'encoded_'+safe)
    original_layers=node('blast','ORIGINAL_LAYERS_WITHOUT_ID',[colored],{'group':'@name=id','negate':0})
    new_id=keep(previous,'NEW_ID_ONLY','@name=id')
    restore=node('merge','PRESERVE_ORIGINAL_MASKS',[original_layers,new_id])
    restored=checkpoint(restore,'final')
    final=node('null','OUT_WORKING_TRANSITION',[restored])
    outc=node('null','OUT_CONTEXT_UNCHANGED',[c])
    if not a.verify:
        final.setDisplayFlag(True);final.setRenderFlag(True)
        original.setDisplayFlag(False)
        g.setComment('L06-only adaptation. Original masks and height retained. Context nearest ID, native masked Layer composites, original Pegasus encoders. Inset 32 m / blur 16 m are local tuning, not tutorial constants.')
        g.layoutChildren();hou.hipFile.save(str(HIP))
    # Whole-domain preservation and complete perimeter categorical equality.
    output=geometry(final);baseline=read(SOURCE/'working/final.bgeo.sc')
    weight=values(read(ROOT/'border_weight.bgeo.sc'),'mask').reshape(ny,nx)
    original_ids=values(baseline,'id').reshape(ny,nx)
    actual=values(output,'id').reshape(ny,nx)
    reference=values(read(ROOT/'context_id_aligned.bgeo.sc'),'id').reshape(ny,nx)
    assert set(np.rint(np.unique(reference)*255).astype(int)).issubset(set(CODES)),'Invalid resampled ID'
    report['invariants']={}
    for p in baseline.prims():
        name=p.attribValue('name')
        if name in ['id','r','g','b','roughness']:continue
        q=volume(output,name)
        assert lattice(q)==lattice(p) and q.allVoxelsAsString()==p.allVoxelsAsString(),name
        report['invariants'][name]='BIT_EXACT'
    core=weight==0
    for name in ['id','r','g','b','roughness']:
        assert np.array_equal(values(output,name)[core.ravel()],values(baseline,name)[core.ravel()]),('interior',name)
    report['unchanged_core_samples']=int(core.sum())
    report['affected_band_samples']=int(np.count_nonzero(~core))
    report['id_changed_samples']=int(np.count_nonzero(actual!=original_ids))
    def perimeter(arr):return np.concatenate([arr[0],arr[-1],arr[:,0],arr[:,-1]])
    assert np.all(perimeter(weight)==1),'Feather must have full border authority'
    ix=np.concatenate([np.arange(nx),np.arange(nx),np.zeros(ny),np.full(ny,nx-1)])
    iy=np.concatenate([np.zeros(nx),np.full(nx,ny-1),np.arange(ny),np.arange(ny)])
    cg=geometry(outc);cl=lattice(volume(cg,'id'))
    cx=np.rint((ox+ix*dx-cl['origin'][0])/cl['x'][0]).astype(int)
    cy=np.rint((oz+iy*dz-cl['origin'][2])/cl['y'][2]).astype(int)
    nearest=values(cg,'id').reshape(2048,2048)[cy,cx]
    report['perimeter_samples']=len(nearest)
    report['perimeter_before']=int(np.count_nonzero(perimeter(original_ids)!=nearest))
    report['perimeter_after_numpy_ties_even']=int(np.count_nonzero(perimeter(actual)!=nearest))
    report['resample_max_float_delta']=float(np.max(np.abs(perimeter(reference)-nearest)))
    # At exactly half a Context voxel, either neighbour is equidistant. VDB's
    # floating transform need not share NumPy's banker's-rounding tie rule.
    fx=(ox+ix*dx-cl['origin'][0])/cl['x'][0]
    fy=(oz+iy*dz-cl['origin'][2])/cl['y'][2]
    txhalf=np.abs(fx-np.floor(fx)-.5)<1e-9
    tyhalf=np.abs(fy-np.floor(fy)-.5)<1e-9
    allowed=np.zeros(len(nearest),dtype=bool)
    reference_codes=np.rint(perimeter(reference)*255)
    context_codes=np.rint(values(cg,'id').reshape(2048,2048)*255)
    for xx in [np.where(txhalf,np.floor(fx),cx).astype(int),np.where(txhalf,np.ceil(fx),cx).astype(int)]:
        for yy in [np.where(tyhalf,np.floor(fy),cy).astype(int),np.where(tyhalf,np.ceil(fy),cy).astype(int)]:
            allowed|=reference_codes==context_codes[yy,xx]
    report['equidistant_samples']=int(np.count_nonzero(txhalf|tyhalf))
    report['resample_nearest_mismatches']=int(np.count_nonzero(~allowed))
    report['perimeter_after']=int(np.count_nonzero(np.rint(perimeter(actual)*255)!=reference_codes))
    assert report['resample_nearest_mismatches']==0,report
    assert report['perimeter_after']==0,report
    report['color_boundary']={}
    positions=[hou.Vector3(float(x),0,float(z)) for x,z in zip(ox+ix*dx,oz+iy*dz)]
    for name in ['r','g','b','roughness']:
        source_volume=volume(cg,name)
        sampled=np.array([source_volume.sample(p) for p in positions],dtype=np.float32)
        old=perimeter(values(baseline,name).reshape(ny,nx))
        new=perimeter(values(output,name).reshape(ny,nx))
        delta=np.abs(new-sampled)
        report['color_boundary'][name]={'before_mean_abs':float(np.mean(np.abs(old-sampled))),'after_mean_abs':float(delta.mean()),'after_max_abs':float(delta.max())}
        assert delta.max()<.001,(name,report['color_boundary'][name])
    report['decoded']={}
    dec=node(original.node('ID_TO_LAYER').type().name(),'VERIFY_DECODER',[final],{'srcname1':'id','dstname1':'mask'})
    for name,code in zip(NAMES,CODES):
        dec.parm('id_layer').set(str(code))
        decoded=values(geometry(dec),'mask')>.5
        selected=actual.ravel()==np.float32(code/255)
        assert np.array_equal(decoded,selected),name
        report['decoded'][name]=int(selected.sum())
        print('DECODED',name,report['decoded'][name],flush=True)
    # Unchanged Context retains the earlier full native replay and decoder proof.
    assert digest(SOURCE/'context/final.bgeo.sc')==json.loads((SOURCE/'context/reopen.json').read_text())['cache_sha256']
    sources=json.loads((ROOT/'source_attribution.json').read_text())['source_hashes']
    for path,sha in sources.items():assert digest(path)==sha,path
    report['retained_source_hashes']=sources
    if not a.verify:
        dec.parm('id_layer').set('0')
        g.layoutChildren()
        hou.hipFile.save(str(HIP))
    report['hip_sha256']=digest(HIP)
    report['script_sha256']=digest(__file__)
    report['status']='NATIVE_SEAM_PASS'
    np.savez_compressed(ROOT/('reopen_previews.npz' if a.verify else 'previews.npz'),weight=weight[::8,::8],before=original_ids[::8,::8],after=actual[::8,::8],perimeter_before=perimeter(original_ids),perimeter_after=perimeter(actual),perimeter_context=nearest)
    (ROOT/('reopen.json' if a.verify else 'repair.json')).write_text(json.dumps(report,indent=2)+'\n')
    print(report['status'],report['perimeter_before'],report['perimeter_after'],flush=True)

if __name__=='__main__':main()
